"""Generate README.md from the files in data/. Run: python3 scripts/build_readme.py

README.md is generated. Edit the JSON files in data/ instead.
"""
import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = "https://github.com/compositional-robot/awesome-compositional-robot-learning"
SITE = "https://compositional-robot.github.io/"

# Keep in sync with scripts/validate.py and the website's app.js.
TOPICS = [
    ("time", "Composing Skills over Time"),
    ("modality", "Composing Modalities & Policies"),
    ("constraints", "Composing Constraints & Objectives"),
    ("programs", "Programs & Symbolic Structure"),
    ("modular", "Modular Architectures"),
    ("benchmarks", "Benchmarks & Analysis"),
]


def load(name):
    return json.loads((ROOT / "data" / name).read_text(encoding="utf-8"))


def anchor(heading):
    keep = "".join(c for c in heading.lower() if c.isalnum() or c in " -")
    return keep.replace(" ", "-")


def links(entry):
    out = []
    for key, label in (("paper", "Paper"), ("project", "Project"), ("code", "Code")):
        if entry.get(key):
            out.append(f"[[{label}]]({entry[key]})")
    return " ".join(out)


def paper_item(p):
    return (
        f"- **{p['title']}**<br>\n"
        f"  {p['authors']}<br>\n"
        f"  *{p['venue']}* {links(p)}<br>\n"
        f"  {p['note']}\n"
    )


def by_recency(items):
    return sorted(items, key=lambda p: (-p["year"], p["title"].lower()))


def main():
    papers = load("papers.json")
    background = load("background.json")
    workshops = load("workshops.json")

    lines = [
        "<!-- This file is generated by scripts/build_readme.py. Edit the files in data/ instead. -->",
        "",
        "# Awesome Compositional Robot Learning [![Awesome](https://awesome.re/badge.svg)](https://awesome.re)",
        "",
        "Robots that generalize by composing what they already know: chaining skills over time, combining",
        "sensing modalities and policies, and assembling constraints, objectives and programs at test time.",
        "",
        f"Browse, filter and search this list at **[compositional-robot.github.io]({SITE})**.",
        "Contributions are welcome, including your own work. See [Contributing](#contributing).",
        "",
        "## Contents",
        "",
        "- [Workshops](#workshops)",
        "- [Papers](#papers)",
    ]
    sections = []
    for tid, label in TOPICS:
        group = [p for p in papers if p["topics"][0] == tid]
        if group:
            sections.append((label, by_recency(group)))
            lines.append(f"  - [{label}](#{anchor(label)})")
    lines += ["- [Background](#background)", "- [Contributing](#contributing)", ""]

    lines += ["## Workshops", ""]
    for w in sorted(workshops, key=lambda w: w["date"], reverse=True):
        d = date.fromisoformat(w["date"])
        lines += [
            f"- **[{w['title']}]({w['url']})**<br>",
            f"  *{w['venue']}*, {d.strftime('%B')} {d.day}, {d.year}, {w['location']}<br>",
            f"  Organizers: {', '.join(w['organizers'])}<br>",
            f"  Speakers: {', '.join(w['speakers'])}",
            "",
        ]

    lines += [
        "## Papers",
        "",
        "Each paper is listed under its primary topic, newest first. "
        f"The [website]({SITE}) also shows papers under their secondary topics.",
        "",
    ]
    for label, group in sections:
        lines += [f"### {label}", ""]
        lines += [paper_item(p) for p in group]

    lines += ["## Background", "", "Earlier work in robotics, control and AI that the ideas above build on.", ""]
    lines += [paper_item(p) for p in sorted(background, key=lambda p: (p["year"], p["title"].lower()))]

    lines += [
        "## Contributing",
        "",
        f"- **Suggest a paper:** [open the form]({REPO}/issues/new?template=add-paper.yml) and a maintainer will add it.",
        "- **Add it yourself:** append an entry to [`data/papers.json`](data/papers.json) and open a pull request.",
        "  This README and the website update automatically after the pull request is merged.",
        "",
        "Scope: robotics work where composition or modularity is the main idea. Your own work is welcome.",
        "See [CONTRIBUTING.md](CONTRIBUTING.md) for the entry format.",
        "",
    ]
    (ROOT / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"README.md: {len(papers)} papers, {len(background)} background, {len(workshops)} workshops")


if __name__ == "__main__":
    main()
